import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {StudyEngine} from '../public/mobile-engine.mjs';
const ids=['cet4','cet6','kaoyan','cet4-core','cet6-core','kaoyan-core','phrases'];
const books=ids.map(id=>JSON.parse(readFileSync(new URL('../data/books/'+id+'.json',import.meta.url),'utf8')));
let disk=null, writes=0, broken=false;
const storage={read:()=>disk,write:text=>{if(broken)throw Error('disk full');disk=text;writes++;}};
let engine=new StudyEngine(books,storage);
assert.equal(engine.bootstrap().books.length,7);
let {session:first}=await engine.request('/api/start',{bookId:'cet4'});
assert.equal(first.words.length,10);
const selected=first.words.slice(0,2).map(w=>w.id);
await assert.rejects(engine.request('/api/round/complete',{bookId:'cet4',sessionId:first.id,selected}),/先查看/);
await engine.request('/api/round/update',{bookId:'cet4',sessionId:first.id,selected,stage:'review'});
await engine.request('/api/settings',{batchSize:7,order:'random'});
engine=new StudyEngine(books,storage);
assert.deepEqual((await engine.request('/api/start',{bookId:'cet4'})).session.selected,selected);
assert.equal(engine.state.progress.cet4.current.stage,'review');
const corrected=[first.words[0].id,first.words[2].id];
const completion={bookId:'cet4',sessionId:first.id,selected:corrected};
assert.equal((await engine.request('/api/round/complete',completion)).added,2);
assert.equal((await engine.request('/api/round/complete',completion)).alreadySaved,true);
assert.equal(engine.bootstrap().totalCount,10);
const next=(await engine.request('/api/start',{bookId:'cet4'})).session;
assert.equal(next.words.length,7);assert.ok(next.words.every(w=>!first.words.some(p=>p.id===w.id)));
await engine.request('/api/settings',{batchSize:10,order:'sequence'});
const six=(await engine.request('/api/start',{bookId:'cet6'})).session;
const common=six.words.find(w=>w.id===corrected[0]);assert.ok(common);
const body={bookId:'cet6',sessionId:six.id,selected:[common.id],stage:'review'};
await engine.request('/api/round/update',body);await engine.request('/api/round/complete',body);
assert.equal(Object.keys(engine.state.unknown).length,2);
assert.equal(engine.state.unknown[common.id].sources.length,2);
const beforeReset=structuredClone(engine.state);
await engine.request('/api/restart',{bookId:'cet4'});
assert.deepEqual(engine.state.progress.cet4,{seen:[],rounds:0,current:null});
assert.deepEqual(engine.state.progress.cet6,beforeReset.progress.cet6);
assert.deepEqual(engine.state.unknown,beforeReset.unknown);assert.deepEqual(engine.state.daily,beforeReset.daily);
await assert.rejects(engine.request('/api/round/update',{bookId:'cet4',sessionId:next.id,selected:[]}),/已经发生变化/);
const backup=engine.exportState();
const review=(await engine.request('/api/start',{bookId:'unknown'})).session;
assert.equal(review.words.length,2);
await engine.request('/api/round/update',{bookId:'unknown',sessionId:review.id,stage:'review',selected:[]});
assert.equal((await engine.request('/api/round/complete',{bookId:'unknown',sessionId:review.id,selected:[]})).removed,2);
assert.equal((await engine.request('/api/start',{bookId:'unknown'})).session,null);
const candidate=engine.previewImport(backup);engine.importState(candidate);
assert.equal(engine.bootstrap().unknownBook.count,2);
const prior=engine.exportState();
for(const bad of ['not json','{}',JSON.stringify({...candidate,settings:{batchSize:0}}),JSON.stringify({...candidate,progress:{cet4:{seen:[],rounds:0,current:{}}}})])assert.throws(()=>engine.previewImport(bad));
assert.equal(engine.exportState(),prior);
broken=true;
await assert.rejects(engine.request('/api/settings',{batchSize:50,order:'sequence'}),/disk full/);
assert.equal(engine.exportState(),prior);broken=false;
for(const batchSize of [0,101,1.5,true])await assert.rejects(engine.request('/api/settings',{batchSize,order:'sequence'}));
console.log(`PASS: 7 bundled books; offline resume, corrected selection, random unseen batches, cross-book deduplication, unknown review, idempotency, isolated reset, validated backup restore, failed-write rollback (${writes} writes).`);
